"""Aggregate-only release-readiness evidence for the PRTI-GH adaptation.

The automated screen in this module is a triage aid.  It deliberately leaves
clinical, privacy, governance, and independent disclosure-control decisions to
named human reviewers and never exports patient values.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path

import pandas as pd

from .prti_data import DEFAULT_PRTI_SOURCE, PRTIDataAdapter, PRTIPreparedData


DEFAULT_CANDIDATE_DIRECTORY = Path(
    "outputs/prti/privacy-candidate-heldout-seed10"
)
DEFAULT_EVIDENCE_DIRECTORY = Path("evidence/prti-release-readiness-v1")

ATTRIBUTE_REVIEW_FILE = "prti_attribute_role_review.csv"
READINESS_FILE = "prti_release_readiness.json"

_DIRECT_IDENTIFIER_NAME = re.compile(
    r"(?:patient|person|child)?(?:name|identifier|recordid|recordnumber)|"
    r"email|phone|telephone|contact|address|gps|latitude|longitude",
    re.IGNORECASE,
)
_EMAIL = re.compile(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", re.IGNORECASE)
_UUID = re.compile(
    r"\b[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-"
    r"[89ab][0-9a-f]{3}-[0-9a-f]{12}\b",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class ReleaseReadinessPaths:
    """Files generated by the aggregate-only readiness review."""

    attribute_review: Path
    readiness: Path


def _text_profile(values: pd.Series) -> dict[str, int | float | bool]:
    """Return value-free text and identifier indicators for one attribute."""

    observed = values.dropna().astype(str)
    if observed.empty:
        return {
            "maximum_characters": 0,
            "maximum_tokens": 0,
            "mean_tokens": 0.0,
            "email_pattern_records": 0,
            "uuid_pattern_records": 0,
            "phone_pattern_records": 0,
            "potential_free_text": False,
        }

    character_counts = observed.str.len()
    token_counts = observed.str.split().str.len()
    email_count = int(observed.str.contains(_EMAIL, na=False).sum())
    uuid_count = int(observed.str.contains(_UUID, na=False).sum())

    def looks_like_phone(value: str) -> bool:
        digits = re.sub(r"\D", "", value)
        return 7 <= len(digits) <= 15 and bool(re.fullmatch(r"[+()\- .0-9]+", value))

    phone_count = int(observed.map(looks_like_phone).sum())
    maximum_characters = int(character_counts.max())
    maximum_tokens = int(token_counts.max())
    return {
        "maximum_characters": maximum_characters,
        "maximum_tokens": maximum_tokens,
        "mean_tokens": float(token_counts.mean()),
        "email_pattern_records": email_count,
        "uuid_pattern_records": uuid_count,
        "phone_pattern_records": phone_count,
        "potential_free_text": maximum_characters >= 120 or maximum_tokens >= 8,
    }


def build_attribute_review(
    original: pd.DataFrame,
    audit: pd.DataFrame,
) -> pd.DataFrame:
    """Build a 106-row review register without exporting source values."""

    required = {
        "position",
        "attribute",
        "role",
        "sourceDtype",
        "distinctNonMissingValues",
        "missingValues",
        "cardinalityPercentage",
        "reviewFlag",
    }
    missing = required - set(audit.columns)
    if missing:
        raise ValueError(f"Candidate input audit is missing columns: {sorted(missing)}")
    if list(audit["attribute"]) != list(original.columns):
        raise ValueError("Candidate audit attributes do not match the reviewed source order.")

    rows: list[dict[str, object]] = []
    for item in audit.to_dict(orient="records"):
        attribute = str(item["attribute"])
        values = original[attribute]
        profile = _text_profile(values) if not pd.api.types.is_numeric_dtype(values) else {
            "maximum_characters": 0,
            "maximum_tokens": 0,
            "mean_tokens": 0.0,
            "email_pattern_records": 0,
            "uuid_pattern_records": 0,
            "phone_pattern_records": 0,
            "potential_free_text": False,
        }
        name_flag = bool(_DIRECT_IDENTIFIER_NAME.search(attribute))
        pattern_flag = any(
            int(profile[key]) > 0
            for key in (
                "email_pattern_records",
                "uuid_pattern_records",
                "phone_pattern_records",
            )
        )
        potential_direct_identifier = name_flag or pattern_flag
        flags: list[str] = []
        if potential_direct_identifier:
            flags.append("potential direct identifier")
        if bool(profile["potential_free_text"]):
            flags.append("potential free text")
        existing_flag = item["reviewFlag"]
        if pd.notna(existing_flag) and str(existing_flag).strip():
            flags.append(str(existing_flag).strip())

        rows.append(
            {
                "position": int(item["position"]),
                "attribute": attribute,
                "current_role": item["role"],
                "source_dtype": item["sourceDtype"],
                "distinct_nonmissing_values": int(item["distinctNonMissingValues"]),
                "missing_values": int(item["missingValues"]),
                "cardinality_percentage": float(item["cardinalityPercentage"]),
                "maximum_characters": profile["maximum_characters"],
                "maximum_tokens": profile["maximum_tokens"],
                "mean_tokens": profile["mean_tokens"],
                "email_pattern_records": profile["email_pattern_records"],
                "uuid_pattern_records": profile["uuid_pattern_records"],
                "phone_pattern_records": profile["phone_pattern_records"],
                "potential_direct_identifier": potential_direct_identifier,
                "potential_free_text": profile["potential_free_text"],
                "automated_review_flags": "; ".join(flags),
                "clinical_review_status": "PENDING",
                "privacy_review_status": "PENDING",
                "data_governance_review_status": "PENDING",
                "approved_release_role": "PENDING",
                "reviewer": "PENDING",
                "review_date": "PENDING",
                "review_rationale": "PENDING",
            }
        )

    review = pd.DataFrame(rows)
    if len(review) != len(original.columns):
        raise AssertionError("The attribute review must contain one row per source column.")
    return review


def build_readiness_record(
    prepared: PRTIPreparedData,
    review: pd.DataFrame,
) -> dict[str, object]:
    """Record bounded research decisions and unresolved external gates."""

    direct_flags = int(review["potential_direct_identifier"].sum())
    free_text_flags = int(review["potential_free_text"].sum())
    flagged_attributes = int(review["automated_review_flags"].ne("").sum())
    return {
        "record_version": "1.0.0",
        "record_date": date.today().isoformat(),
        "dataset": "PRTI-GH",
        "source_sha256": prepared.summary["source_sha256_before"],
        "rows": len(prepared.original),
        "attributes": len(prepared.original.columns),
        "external_release_status": "BLOCKED_PENDING_HUMAN_AND_CUSTODIAN_APPROVALS",
        "experiment_scope_decision": {
            "remaining_full_grid_points": 181,
            "required_for_current_claims": False,
            "decision": "DO_NOT_RUN_FOR_CURRENT_CLAIMS",
            "rationale": (
                "The current claims are bounded to the predeclared one-factor study, "
                "the four-candidate multi-seed robustness study, and the held-out "
                "candidate. They do not claim an exhaustive grid search or a global "
                "parameter optimum. Running the remaining 181 points would be a new "
                "exploratory study, not validation required by the current claims."
            ),
            "reopen_if": [
                "a claim of exhaustive Appendix A grid coverage is proposed",
                "a claim of globally best PRTI-GH hyperparameters is proposed",
                "a reviewer or preregistered follow-up protocol requires the full grid",
            ],
        },
        "downstream_utility_decision": {
            "required_for_current_claims": False,
            "decision": "NOT_RUN_FOR_CURRENT_CLAIMS",
            "rationale": (
                "The current result is an anonymization and disclosure-metric study. "
                "It explicitly makes no claim that predictive or clinical task utility "
                "is preserved. A utility experiment needs a named downstream outcome, "
                "task, split protocol, metrics, and acceptable degradation threshold."
            ),
            "reopen_if": [
                "the release is proposed for a defined predictive or clinical task",
                "the project claims downstream machine-learning utility preservation",
                "the data custodian specifies a task-specific utility requirement",
            ],
        },
        "automated_attribute_screen": {
            "status": "COMPLETE_TRIAGE_ONLY",
            "attributes_reviewed": len(review),
            "attributes_with_any_automated_flag": flagged_attributes,
            "potential_direct_identifier_attributes": direct_flags,
            "potential_free_text_attributes": free_text_flags,
            "patient_values_exported": False,
            "boundary": (
                "Name, pattern, length, missingness, cardinality, and current-role "
                "screening cannot replace contextual human review."
            ),
        },
        "release_gates": [
            {
                "gate": "data custodian threat model and intended recipient",
                "status": "PENDING_EXTERNAL",
            },
            {
                "gate": "clinical review of all 106 attribute roles",
                "status": "PENDING_EXTERNAL",
            },
            {
                "gate": "privacy and data-governance review of all 106 roles",
                "status": "PENDING_EXTERNAL",
            },
            {
                "gate": "human direct-identifier and free-text inspection",
                "status": "PENDING_EXTERNAL",
            },
            {
                "gate": "independent disclosure-control review",
                "status": "PENDING_EXTERNAL",
            },
            {
                "gate": "publication author identity and licence",
                "status": "PENDING_OWNER_DECISION",
            },
        ],
    }


def generate_release_readiness(
    source_path: Path = DEFAULT_PRTI_SOURCE,
    candidate_directory: Path = DEFAULT_CANDIDATE_DIRECTORY,
    evidence_directory: Path = DEFAULT_EVIDENCE_DIRECTORY,
) -> ReleaseReadinessPaths:
    """Generate the aggregate-only review register and decision record."""

    prepared = PRTIDataAdapter(source_path=source_path).prepare()
    audit_path = candidate_directory / "prti_input_audit.csv"
    if not audit_path.is_file():
        raise FileNotFoundError(f"Held-out candidate audit not found: {audit_path}")
    audit = pd.read_csv(audit_path)
    review = build_attribute_review(prepared.original, audit)
    readiness = build_readiness_record(prepared, review)

    evidence_directory.mkdir(parents=True, exist_ok=True)
    review_path = evidence_directory / ATTRIBUTE_REVIEW_FILE
    readiness_path = evidence_directory / READINESS_FILE
    review.to_csv(review_path, index=False)
    readiness_path.write_text(
        json.dumps(readiness, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return ReleaseReadinessPaths(review_path, readiness_path)
